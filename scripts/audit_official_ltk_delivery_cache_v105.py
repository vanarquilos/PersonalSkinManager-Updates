#!/usr/bin/env python3
"""Read-only inspection of LTK Manager's OFFICIAL delivery cache.

This does NOT download or run patcher code, emulate an attested manager,
read delivery.json authentication tokens, or claim skin rendering.
The cache is generated by a real official manager installation. A user
may configure a nondefault data directory, so --data-dir is supported.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
import os
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from injection.tools.patcher import (  # noqa: E402
    LTK_PATCHER_HOST,
    LTK_PATCHER_DLL,
    read_game_build,
    read_dll_eol,
)

DIGEST = re.compile(r"[0-9a-fA-F]{64}\Z")


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest().lower()


def probe(root: Path, game_build: int | None) -> list[dict]:
    """List at most 50 staged pairs, never reading delivery.json tokens."""
    if not root.is_dir() or root.is_symlink():
        return []
    try:
        dirs = sorted(path for path in root.iterdir() if path.is_dir()
                      and not path.is_symlink() and DIGEST.fullmatch(path.name))
    except OSError:
        return []
    result = []
    for directory in dirs[:50]:
        dll = directory / LTK_PATCHER_DLL
        host = directory / LTK_PATCHER_HOST
        entry = {
            "directory": str(directory),
            "dll_sha256": None,
            "host_sha256": None,
            "cutoff_utc": None,
            "status": "INCOMPLETE",
        }
        if (not dll.is_file() or not host.is_file()
                or dll.is_symlink() or host.is_symlink()):
            result.append(entry)
            continue
        try:
            digest = sha256(dll)
            entry["dll_sha256"] = digest
            entry["host_sha256"] = sha256(host)
            if digest != directory.name.lower():
                entry["status"] = "DIGEST_DIRECTORY_MISMATCH"
                result.append(entry)
                continue
            cutoff = read_dll_eol(dll)
        except (OSError, ValueError):
            entry["status"] = "UNREADABLE"
            result.append(entry)
            continue
        if cutoff is None:
            entry["status"] = "UNKNOWN_DLL_CUTOFF"
        else:
            entry["cutoff_utc"] = datetime.fromtimestamp(
                cutoff, timezone.utc
            ).isoformat()
            entry["status"] = (
                "EXPIRED_FOR_INSTALLED_GAME"
                if game_build is not None and game_build > cutoff
                else "CUTOFF_NOT_EXCEEDED"
                if game_build is not None else "UNKNOWN_GAME_BUILD"
            )
        result.append(entry)
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--league-dir", type=Path, required=True)
    parser.add_argument(
        "--data-dir", type=Path, action="append", default=[],
        help="Official LTK Manager mod storage directory (patcher/ is appended)",
    )
    args = parser.parse_args()
    roots = list(args.data_dir)
    if not roots:
        for name in ("APPDATA", "LOCALAPPDATA"):
            path = os.environ.get(name)
            if path:
                roots.append(Path(path) / "dev.leaguetoolkit.manager")
    game = read_game_build(args.league_dir)
    if game is None:
        game = read_game_build(args.league_dir / "Game")
    entries = []
    for data_root in dict.fromkeys(roots):
        entries.extend(probe(data_root / "patcher", game))
    print(json.dumps({
        "game_build_utc": datetime.fromtimestamp(
            game, timezone.utc
        ).isoformat() if game is not None else None,
        "candidates": entries,
        "notice": (
            "Read-only local cache inventory; no service token or attestations "
            "were read. SHA-256, an acceptable cutoff and file presence are "
            "NOT proof of official release-manifest authenticity, applicable "
            "licensing, correct process integrity, or in-game rendering. "
            "Use only a properly signed and supported official manager "
            "to populate this cache."
        ),
    }, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
